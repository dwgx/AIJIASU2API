export const dictionaries: Record<Language, Record<string, string>> = { en: EN, zh: ZH }

function interpolate(template: string, params?: TranslationParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

/** Pure lookup: English is the fallback, then the key itself. */
export function translate(lang: Language, key: string, params?: TranslationParams): string {
  const value = dictionaries[lang][key] ?? EN[key as TranslationKey] ?? key
  return interpolate(value, params)
}

function initialLanguage(): Language {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (stored === 'zh' || stored === 'en') return stored
  } catch {
    // Storage can be unavailable (private mode); fall through to the browser hint.
  }
  const hint = typeof navigator === 'undefined' ? '' : navigator.language
  return hint.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

interface I18nContextValue {
  lang: Language
  setLang: (lang: Language) => void
  t: (key: string, params?: TranslationParams) => string
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  setLang: () => {},
  t: (key, params) => translate('en', key, params),
})

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(initialLanguage)

  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang)
    } catch {
      // The in-memory choice still applies for this session.
    }
  }, [lang])

  const setLang = useCallback((next: Language) => setLangState(next), [])
  const t = useCallback(
    (key: string, params?: TranslationParams) => translate(lang, key, params),
    [lang],
  )

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
