// deviceRecordLocked returns the live record; callers must copy before
// unlocking.
func (s *Store) deviceRecordLocked(id string) *DeviceRecord {
	if s.devicePool == nil {
		return nil
	}
	return s.devicePool[id]
}

func (s *Store) devicePoolLocked() []DeviceRecord {
	out := make([]DeviceRecord, 0, len(s.devicePool))
	for _, rec := range s.devicePool {
		out = append(out, cloneDeviceRecord(*rec))
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].CreatedAt != out[j].CreatedAt {
			return out[i].CreatedAt < out[j].CreatedAt
		}
		return out[i].ID < out[j].ID
	})
	return out
}

func (s *Store) newDeviceIDLocked() string {
	for {
		id, err := randomHex(8)
		if err != nil {
			// crypto/rand failure is fatal for identity generation; return a
			// value that cannot collide with a real record and let the caller
			// fail the seal.
			return ""
		}
		id = DeviceIDPrefix + id
		if _, taken := s.devicePool[id]; !taken {
			return id
		}
	}
}

func (s *Store) deviceAppendEventLocked(rec *DeviceRecord, action, actor, detail string) {
	rec.History = append(rec.History, DeviceEvent{
		At: iso(s.now()), Action: action, Actor: actor, Detail: detail,
	})
	if len(rec.History) > DeviceHistoryCap {
		rec.History = rec.History[len(rec.History)-DeviceHistoryCap:]
	}
}

func appendDeviceAlias(aliases []string, alias string) []string {
	if alias == "" {
		return aliases
	}
	for _, existing := range aliases {
		if existing == alias {
			return aliases
		}
	}
	aliases = append(aliases, alias)
	if len(aliases) > DeviceAliasCap {
		aliases = aliases[len(aliases)-DeviceAliasCap:]
	}
	return aliases
}

func cloneDeviceRecord(rec DeviceRecord) DeviceRecord {
	rec.Hashes = cloneStringMap(rec.Hashes)
	rec.Claims = cloneStringMap(rec.Claims)
	rec.AccountKeyAliases = append([]string(nil), rec.AccountKeyAliases...)
	rec.History = append([]DeviceEvent(nil), rec.History...)
	rec.AssignedAt = cloneStringPtr(rec.AssignedAt)
	rec.PresentedAt = cloneStringPtr(rec.PresentedAt)
	rec.FirstSeenAt = cloneStringPtr(rec.FirstSeenAt)
	rec.LastSeenAt = cloneStringPtr(rec.LastSeenAt)
	rec.RetiredAt = cloneStringPtr(rec.RetiredAt)
	return rec
}

func cloneDeviceMaterial(m DeviceMaterial) DeviceMaterial {
	m.PresentedAt = cloneStringPtr(m.PresentedAt)
	m.AccountKeyAliases = append([]string(nil), m.AccountKeyAliases...)
	return m
}

func cloneStringMap(in map[string]string) map[string]string {
	if in == nil {
		return nil
	}
	out := make(map[string]string, len(in))
	for key, value := range in {
		out[key] = value
	}
	return out
}

func cloneStringPtr(value *string) *string {
	if value == nil {
		return nil
	}
	copied := *value
	return &copied
}

