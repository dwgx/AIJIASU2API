// This file implements the P0 device identity pool from DESIGN-DEVICE-POOL.
// A DeviceRecord is the non-secret index entry persisted in the snapshot; the
// raw vendor identifiers and the machine code live only in a sealed material
// file (DeviceSealer), keyed by record id. Nothing in this file logs or
// returns a raw identity outside AccountDeviceMaterial and the encrypted
// export payload.

