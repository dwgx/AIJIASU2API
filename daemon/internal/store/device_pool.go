var deviceIDPattern = regexp.MustCompile(`^dev_[0-9a-f]{16}$`)

func isLowerHex(value string, n int) bool {
	if len(value) != n {
		return false
	}
	for _, c := range value {
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}

func isSHA256Hex(value string) bool {
	value = strings.TrimPrefix(value, "sha256:")
	return isLowerHex(value, 64)
}

func randomHex(nBytes int) (string, error) {
	buf := make([]byte, nBytes)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("store: random bytes: %w", err)
	}
	return hex.EncodeToString(buf), nil
}

// deviceFingerprint is the stable identity fingerprint (version excluded).
func deviceFingerprint(machineCode string, id DeviceIdentity) string {
	parts := []string{
		"ajs.device.fingerprint.v1", machineCode,
		id.UID, id.OSDID, id.CUID, id.CSEID,
		id.OSP, id.OSD, id.OSV, id.DIM,
		id.Site, id.HW, id.OSLang,
		strconv.Itoa(id.TZMin),
		id.Lang, id.InstMkt, id.Vrf,
	}
	sum := sha256.Sum256([]byte(strings.Join(parts, "\x1f")))
	return "sha256:" + hex.EncodeToString(sum[:])
}

// deviceAccountKey matches a retired record to a re-added account.
func deviceAccountKey(family model.Platform, username string) string {
	sum := sha256.Sum256([]byte("ajs.account.v1\x1f" + string(family) + "\x1f" + username))
	return "sha256:" + hex.EncodeToString(sum[:])
}

// deviceHash is the UI/API convention: sha256 prefix, first 16 hex.
func deviceHash(value string) string {
	if value = strings.TrimSpace(value); value == "" {
		return ""
	}
	sum := sha256.Sum256([]byte(value))
	return "sha256:" + hex.EncodeToString(sum[:])[:16]
}

func deviceHashes(id DeviceIdentity, machineCode string) map[string]string {
	return map[string]string{
		"uid":     deviceHash(id.UID),
		"osdid":   deviceHash(id.OSDID),
		"cuid":    deviceHash(id.CUID),
		"cseid":   deviceHash(id.CSEID),
		"machine": deviceHash(machineCode),
	}
}

// deviceClaims carries only public claims. cseid is deliberately hashed, not
// claimed: for OpenAJS it equals _os_did.
func deviceClaims(id DeviceIdentity) map[string]string {
	claims := map[string]string{}
	for key, value := range map[string]string{
		"site":    id.Site,
		"version": id.Version,
		"osp":     id.OSP,
		"osd":     id.OSD,
		"osv":     id.OSV,
		"lang":    id.Lang,
	} {
		if value = strings.TrimSpace(value); value != "" {
			claims[key] = value
		}
	}
	return claims
}

// familyOf derives the device family from an identity, falling back to the
// account platform. It rejects anything it cannot prove instead of guessing.
func familyOf(id DeviceIdentity, accountPlatform model.Platform) (model.Platform, error) {
	switch {
	case id.OSP == "linux" || id.CSEID == "linux" || isLowerHex(id.UID, 20):
		return model.PlatformLinux, nil
	case id.OSP == "android" || isLowerHex(id.UID, 22):
		return model.PlatformAndroid, nil
	}
	switch accountPlatform {
	case model.PlatformLinux, model.PlatformAndroid:
		return accountPlatform, nil
	default:
		return "", invalidf("device identity has no recognisable family")
	}
}

// identityFromDevice mirrors account.Identify for the store's generators.
func identityFromDevice(dev apifacade.Device) DeviceIdentity {
	cuid := dev.CUID
	if cuid == "" {
		cuid = dev.DeviceID
	}
	cseid := dev.CSEID
	if cseid == "" {
		cseid = cuid
	}
	return DeviceIdentity{
		UID:     dev.UID,
		OSDID:   dev.DeviceID,
		CUID:    cuid,
		CSEID:   cseid,
		OSP:     dev.Platform,
		OSD:     dev.OSDevice,
		OSV:     dev.OSVersion,
		DIM:     dev.OSDim,
		Version: dev.Version,
		Site:    dev.Site,
		HW:      dev.OSHW,
		OSLang:  dev.OSLang,
		TZMin:   dev.TZMinutes,
		Lang:    dev.Lang,
		InstMkt: dev.InstMkt,
		Vrf:     dev.Vrf,
	}
}

// DeviceGenerateSpec is one generator input. Index is part of the derivation
// domain so a batch is reproducible from one seed.
type DeviceGenerateSpec struct {
	Profile DeviceProfile
	Index   uint32
	Seed    []byte
	DimMode string
}

// DeviceGenerator produces one material. Implementations are compiled in; the
// registry is not a plugin loader.
type DeviceGenerator interface {
	Name() string
	Generate(spec DeviceGenerateSpec) (DeviceMaterial, error)
}

var deviceGenerators = map[string]DeviceGenerator{
	DeviceAlgorithmRandom: randomGenerator{},
	DeviceAlgorithmHMAC:   hmacGenerator{},
}

// RegisterDeviceGenerator adds a compiled-in generator. It exists for forks
// and tests; the daemon registers none at runtime.
func RegisterDeviceGenerator(g DeviceGenerator) {
	if g == nil || g.Name() == "" {
		return
	}
	deviceGenerators[g.Name()] = g
}

// DeviceGeneratorByName resolves a generator; unknown names fail closed.
func DeviceGeneratorByName(name string) (DeviceGenerator, bool) {
	g, ok := deviceGenerators[name]
	return g, ok
}

func validDeviceAlgorithm(name string) bool {
	switch name {
	case DeviceAlgorithmRandom, DeviceAlgorithmHMAC, DeviceAlgorithmImport, DeviceAlgorithmLegacy:
		return true
	default:
		_, ok := deviceGenerators[name]
		return ok
	}
}

// validateDeviceMaterial enforces DESIGN-DEVICE-POOL §7.5 for every generator
// and every import.
func validateDeviceMaterial(profile DeviceProfile, m DeviceMaterial) error {
	if !isLowerHex(m.MachineCode, 64) {
		return invalidf("device machine code must be 64 lowercase hex characters")
	}
	id := m.Identity
	switch profile.Family {
	case model.PlatformLinux:
		switch {
		case !isLowerHex(id.UID, 20):
			return invalidf("linux device uid must be 20 lowercase hex characters")
		case !isLowerHex(id.OSDID, 16):
			return invalidf("linux device osdid must be 16 lowercase hex characters")
		case id.CUID != id.UID:
			return invalidf("linux device cuid must equal uid")
		case id.CSEID != "linux":
			return invalidf("linux device cseid must be linux")
		case id.OSP != "linux":
			return invalidf("linux device osp must be linux")
		case !strings.HasPrefix(id.DIM, "lid="):
			return invalidf("linux device dim must start with lid=")
		case id.Site != "ajs":
			return invalidf("device site must be ajs")
		case id.Lang != "en":
			return invalidf("linux device lang must be en")
		}
	case model.PlatformAndroid:
		switch {
		case !isLowerHex(id.UID, 22):
			return invalidf("android device uid must be 22 lowercase hex characters")
		case id.UID[18:] != strings.ToLower(apifacade.DualHashHex([]byte(id.UID[:18]))[:4]):
			return invalidf("android device uid checksum is invalid")
		case !isLowerHex(id.OSDID, 16):
			return invalidf("android device osdid must be 16 lowercase hex characters")
		case id.CUID != id.OSDID || id.CSEID != id.OSDID:
			return invalidf("android device cuid and cseid must equal osdid")
		case id.OSP != "android":
			return invalidf("android device osp must be android")
		case id.DIM != `{"asid":"`+id.OSDID+`"}`:
			return invalidf("android device dim must carry the asid claim")
		case id.Site != "ajs":
			return invalidf("device site must be ajs")
		case id.Lang != "zh_cn":
			return invalidf("android device lang must be zh_cn")
		case id.InstMkt != "google" && id.InstMkt != "amazon" && id.InstMkt != "":
			return invalidf("android device instMkt must be google, amazon or empty")
		}
	default:
		return invalidf("device profile family must be linux or android")
	}
	if id.Version != profile.ClientVersion {
		return invalidf("device version %q does not match profile %q", id.Version, profile.ClientVersion)
	}
	if m.Fingerprint != deviceFingerprint(m.MachineCode, id) {
		return invalidf("device fingerprint does not match its identity")
	}
	return nil
}

// hmacSHA256Bytes derives a keyed digest. The key is the raw machine code.
func hmacSHA256Bytes(key []byte, message string) []byte {
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(message))
	return mac.Sum(nil)
}

func hmacSHA256Hex(key []byte, message string, nBytes int) string {
	return hex.EncodeToString(hmacSHA256Bytes(key, message)[:nBytes])
}

type randomGenerator struct{}

func (randomGenerator) Name() string { return DeviceAlgorithmRandom }

// Generate builds the same wire formats account.NewDeviceForProfile builds,
// plus the random machine code. The Linux descriptor is the captured literal;
// the Android descriptor is fixed so a record is reproducible on any host.
func (randomGenerator) Generate(spec DeviceGenerateSpec) (DeviceMaterial, error) {
	machineCode, err := randomHex(32)
	if err != nil {
		return DeviceMaterial{}, err
	}
	var identity DeviceIdentity
	switch spec.Profile.Family {
	case model.PlatformLinux:
		dev := apifacade.Linux423Device()
		dev.Version = spec.Profile.ClientVersion
		if err := dev.EnsureLinuxIDs(); err != nil {
			return DeviceMaterial{}, fmt.Errorf("store: linux device ids: %w", err)
		}
		if spec.DimMode == "derived" {
			key, _ := hex.DecodeString(machineCode)
			dev.OSDim = "lid=" + hmacSHA256Hex(key, "ajs.device.v1/dim/lid", 16) +
				"," + hmacSHA256Hex(key, "ajs.device.v1/dim/machine-id", 16)
		}
		identity = identityFromDevice(dev)
	case model.PlatformAndroid:
		dev := apifacade.DefaultDevice()
		dev.Version = spec.Profile.ClientVersion
		dev.TZMinutes = 0
		if err := dev.EnsureIDs(); err != nil {
			return DeviceMaterial{}, fmt.Errorf("store: android device ids: %w", err)
		}
		dev.CUID = dev.DeviceID
		dev.CSEID = dev.DeviceID
		dev.OSDim = `{"asid":"` + dev.DeviceID + `"}`
		identity = identityFromDevice(dev)
	default:
		return DeviceMaterial{}, invalidf("device profile family must be linux or android")
	}
	material := DeviceMaterial{
		Format:      DeviceMaterialFormat,
		Version:     DeviceMaterialVersion,
		MachineCode: machineCode,
		Identity:    identity,
		Platform:    spec.Profile.Family,
		Profile:     spec.Profile.Name,
		Algorithm:   DeviceAlgorithmRandom,
		Fingerprint: deviceFingerprint(machineCode, identity),
	}
	if err := validateDeviceMaterial(spec.Profile, material); err != nil {
		return DeviceMaterial{}, err
	}
	return material, nil
}

type hmacGenerator struct{}

func (hmacGenerator) Name() string { return DeviceAlgorithmHMAC }

// Generate is the normative hmac-sha256/v1 derivation from §7.3. The seed is
// never persisted; the machine code it produces is.
func (hmacGenerator) Generate(spec DeviceGenerateSpec) (DeviceMaterial, error) {
	var machineCode string
	if len(spec.Seed) == 0 {
		random, err := randomHex(32)
		if err != nil {
			return DeviceMaterial{}, err
		}
		machineCode = random
	} else {
		var index [4]byte
		binary.BigEndian.PutUint32(index[:], spec.Index)
		machineCode = hex.EncodeToString(hmacSHA256Bytes(spec.Seed, "ajs.device.machine.v1"+string(index[:])))
	}
	key, err := hex.DecodeString(machineCode)
	if err != nil {
		return DeviceMaterial{}, deviceInvalidf(DeviceReasonSeedInvalid, "device machine code is malformed")
	}
	osdid := hmacSHA256Hex(key, "ajs.device.v1/osdid", 8)
	var identity DeviceIdentity
	switch spec.Profile.Family {
	case model.PlatformLinux:
		uid := hmacSHA256Hex(key, "ajs.device.v1/uid/linux", 10)
		dim := apifacade.Linux423Device().OSDim
		if spec.DimMode == "derived" {
			dim = "lid=" + hmacSHA256Hex(key, "ajs.device.v1/dim/lid", 16) +
				"," + hmacSHA256Hex(key, "ajs.device.v1/dim/machine-id", 16)
		}
		identity = DeviceIdentity{
			UID: uid, OSDID: osdid, CUID: uid, CSEID: "linux",
			OSP: "linux", OSD: "x86_64", OSV: apifacade.Linux423Device().OSVersion, DIM: dim,
			Version: spec.Profile.ClientVersion, Site: "ajs", Lang: "en",
		}
	case model.PlatformAndroid:
		base := hmacSHA256Hex(key, "ajs.device.v1/uid/android", 9)
		uid := base + strings.ToLower(apifacade.DualHashHex([]byte(base))[:4])
		identity = DeviceIdentity{
			UID: uid, OSDID: osdid, CUID: osdid, CSEID: osdid,
			OSP: "android", OSD: "Xiaomi 23013RK75C", OSV: "13",
			DIM:     `{"asid":"` + osdid + `"}`,
			Version: spec.Profile.ClientVersion, Site: "ajs", HW: "qcom",
			OSLang: "zh-Hans-CN", TZMin: 0, Lang: "zh_cn", InstMkt: "google",
		}
	default:
		return DeviceMaterial{}, invalidf("device profile family must be linux or android")
	}
	material := DeviceMaterial{
		Format:      DeviceMaterialFormat,
		Version:     DeviceMaterialVersion,
		MachineCode: machineCode,
		Identity:    identity,
		Platform:    spec.Profile.Family,
		Profile:     spec.Profile.Name,
		Algorithm:   DeviceAlgorithmHMAC,
		Fingerprint: deviceFingerprint(machineCode, identity),
	}
	if err := validateDeviceMaterial(spec.Profile, material); err != nil {
		return DeviceMaterial{}, err
	}
	return material, nil
}

