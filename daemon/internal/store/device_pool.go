// profileForVersion maps a stored identity version to a profile name.
func profileForVersion(version string) string {
	for name, profile := range deviceProfileRegistry {
		if profile.ClientVersion == version {
			return name
		}
	}
	return "legacy/unknown"
}

// DevicePoolConfig holds the operator knobs from DESIGN-DEVICE-POOL §7.6.
// RetentionDays < 0 selects the default (90); 0 keeps tombstones forever.
type DevicePoolConfig struct {
	Algorithm     string
	DimMode       string
	RestoreMode   string
	RetentionDays int
	Max           int
	Mode          string
	Strict        bool
	Seed          []byte
}

func defaultDevicePoolConfig() DevicePoolConfig {
	return DevicePoolConfig{
		Algorithm:     DeviceAlgorithmRandom,
		DimMode:       "legacy",
		RestoreMode:   "auto",
		RetentionDays: DeviceRetentionDays,
		Max:           DevicePoolMax,
		Mode:          "on_demand",
	}
}

// DefaultDevicePoolConfig returns the §7.6 defaults. Build an override from
// it (cfg := DefaultDevicePoolConfig(); cfg.Max = 10) so a zero RetentionDays
// keeps its meaning (0 = keep tombstones forever) only when set explicitly.
func DefaultDevicePoolConfig() DevicePoolConfig { return defaultDevicePoolConfig() }

func (c DevicePoolConfig) normalized() DevicePoolConfig {
	out := defaultDevicePoolConfig()
	if c.Algorithm != "" {
		out.Algorithm = c.Algorithm
	}
	if c.DimMode != "" {
		out.DimMode = c.DimMode
	}
	if c.RestoreMode != "" {
		out.RestoreMode = c.RestoreMode
	}
	if c.RetentionDays >= 0 {
		out.RetentionDays = c.RetentionDays
	}
	if c.Max > 0 {
		out.Max = c.Max
	}
	if c.Mode != "" {
		out.Mode = c.Mode
	}
	out.Strict = c.Strict
	out.Seed = append([]byte(nil), c.Seed...)
	return out
}

// ConfigureDevicePool replaces the pool knobs. It must be called before the
// pool is used; the daemon does it once at startup. Start from
// DefaultDevicePoolConfig() and override fields; the fully zero value resets
// every knob to its default.
func (s *Store) ConfigureDevicePool(cfg DevicePoolConfig) error {
	zero := cfg.Algorithm == "" && cfg.DimMode == "" && cfg.RestoreMode == "" &&
		cfg.RetentionDays == 0 && cfg.Max == 0 && cfg.Mode == "" && !cfg.Strict && len(cfg.Seed) == 0
	if zero {
		cfg = defaultDevicePoolConfig()
	}
	if cfg.Algorithm != "" {
		if _, ok := DeviceGeneratorByName(cfg.Algorithm); !ok {
			return deviceInvalidf(DeviceReasonAlgorithmUnknown, "unknown device algorithm %q", cfg.Algorithm)
		}
	}
	switch cfg.DimMode {
	case "", "legacy", "derived":
	default:
		return invalidf("device dim mode must be legacy or derived")
	}
	switch cfg.RestoreMode {
	case "", "auto", "manual", "off":
	default:
		return invalidf("device restore mode must be auto, manual or off")
	}
	switch cfg.Mode {
	case "", "on_demand", "preallocated":
	default:
		return invalidf("device pool mode must be on_demand or preallocated")
	}
	if cfg.RetentionDays > 3650 {
		return invalidf("device retention days must be at most 3650")
	}
	if cfg.Max > DevicePoolHardMax {
		return invalidf("device pool max must be at most %d", DevicePoolHardMax)
	}
	normalized := cfg.normalized()
	s.mu.Lock()
	s.deviceCfg = normalized
	s.mu.Unlock()
	return nil
}

// DevicePoolEnabled reports whether the sealed material store is wired.
func (s *Store) DevicePoolEnabled() bool { return s.deviceSealer != nil }

// DevicePoolWarnings returns the load-time material warnings (missing or
