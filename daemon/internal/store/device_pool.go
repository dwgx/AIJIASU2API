// bindRestoredDevice binds a tombstone selected by automatic restore.
func (s *Store) bindRestoredDevice(accountID, deviceID string, keys []string, label string) (DeviceMaterial, error) {
	s.mu.RLock()
	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		s.mu.RUnlock()
		return DeviceMaterial{}, deviceNotFoundf("device %q not found", deviceID)
	}
	recCopy := cloneDeviceRecord(*rec)
	material, cached := s.deviceMaterial[deviceID]
	s.mu.RUnlock()
	if _, known := DeviceProfileByName(recCopy.Profile); !known {
		return DeviceMaterial{}, deviceInvalidf(DeviceReasonProfileMismatch,
			"device %q uses unavailable profile %q", deviceID, recCopy.Profile)
	}
	if !cached {
		opened, err := s.openDeviceMaterial(deviceID)
		if err != nil {
			return DeviceMaterial{}, deviceMaterialMissingf("device %q material is missing or corrupt", deviceID)
		}
		if opened.Fingerprint != recCopy.Fingerprint {
			return DeviceMaterial{}, deviceMaterialMissingf("device %q material fingerprint does not match the record", deviceID)
		}
		material = opened
	}
	now := iso(s.now())
	if material.PresentedAt == nil {
		material.PresentedAt = &now
	}
	if err := s.sealDeviceMaterial(material); err != nil {
		return DeviceMaterial{}, err
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	current := s.deviceRecordLocked(deviceID)
	if current == nil || current.State != DeviceRetired || current.AssignedAccountID != "" {
		return DeviceMaterial{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q changed while it was being restored", deviceID)
	}
	if boundID, ok := s.deviceBindings[accountID]; ok {
		return DeviceMaterial{}, deviceConflictf(DeviceReasonAlreadyBound,
			"account %q is already bound to device %q", accountID, boundID)
	}
	if !deviceRecordHasKey(current, keys) {
		return DeviceMaterial{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q was retired for a different account key", deviceID)
	}
	current.State = DeviceAssigned
	current.AssignedAccountID = accountID
	current.AssignedAt = &now
	current.PresentedAt = cloneStringPtr(material.PresentedAt)
	current.RetiredAt = nil
	current.RetiredReason = ""
	s.deviceBindings[accountID] = current.ID
	s.deviceMaterial[current.ID] = cloneDeviceMaterial(material)
	s.devices[accountID] = material.Identity
	s.deviceAppendEventLocked(current, "restored", "system", "candidate=auto")
	s.addAuditLocked(model.SeverityInfo, "system", "device.restore", current.ID,
		"account="+label+" candidate=auto")
	return cloneDeviceMaterial(material), nil
}

// bindAvailableDevice binds a preallocated record at first login.
func (s *Store) bindAvailableDevice(accountID, deviceID, label string) (DeviceMaterial, error) {
	s.mu.RLock()
	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		s.mu.RUnlock()
		return DeviceMaterial{}, deviceNotFoundf("device %q not found", deviceID)
	}
	recCopy := cloneDeviceRecord(*rec)
	idx := s.accountIndexLocked(accountID)
	username := ""
	if idx >= 0 {
		username = s.accounts[idx].Username
	}
	material, cached := s.deviceMaterial[deviceID]
	s.mu.RUnlock()
	if idx < 0 {
		return DeviceMaterial{}, notFoundf("account %q not found", accountID)
	}
	if !cached {
		opened, err := s.openDeviceMaterial(deviceID)
		if err != nil {
			return DeviceMaterial{}, deviceMaterialMissingf("device %q material is missing or corrupt", deviceID)
		}
		material = opened
	}
	if material.Fingerprint != recCopy.Fingerprint {
		return DeviceMaterial{}, deviceMaterialMissingf("device %q material fingerprint does not match the record", deviceID)
	}
	now := iso(s.now())
	accountKey := deviceAccountKey(recCopy.Platform, username)
	alias := deviceAccountKey(recCopy.Platform, strings.ToLower(username))
	material.PresentedAt = &now
	material.AccountKey = accountKey
	material.AccountKeyAliases = appendDeviceAlias(material.AccountKeyAliases, alias)
	if err := s.sealDeviceMaterial(material); err != nil {
		return DeviceMaterial{}, err
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	current := s.deviceRecordLocked(deviceID)
	if current == nil || current.State != DeviceAvailable || current.PresentedAt != nil {
		return DeviceMaterial{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q changed while it was being assigned", deviceID)
	}
	if boundID, ok := s.deviceBindings[accountID]; ok {
		return DeviceMaterial{}, deviceConflictf(DeviceReasonAlreadyBound,
			"account %q is already bound to device %q", accountID, boundID)
	}
	idx = s.accountIndexLocked(accountID)
	if idx < 0 {
		return DeviceMaterial{}, notFoundf("account %q not found", accountID)
	}
	current.State = DeviceAssigned
	current.AssignedAccountID = accountID
	current.AssignedAt = &now
	current.PresentedAt = &now
	current.AccountKey = accountKey
	current.AccountKeyAliases = appendDeviceAlias(current.AccountKeyAliases, alias)
	s.deviceBindings[accountID] = current.ID
	s.deviceMaterial[current.ID] = cloneDeviceMaterial(material)
	s.devices[accountID] = material.Identity
	s.deviceAppendEventLocked(current, "assigned", "system", "source=pool")
	s.addAuditLocked(model.SeverityInfo, "system", "device.assign", current.ID,
		"account="+label+" source=pool")
	return cloneDeviceMaterial(material), nil
}

// AccountDeviceMaterial returns the sealed identity of a bound account. A
// missing or corrupt material reports ErrDeviceMaterialMissing; it never
// falls back to generating a new identity.
func (s *Store) AccountDeviceMaterial(accountID string) (DeviceMaterial, error) {
	s.mu.RLock()
	recID, bound := s.deviceBindings[accountID]
	material, cached := s.deviceMaterial[recID]
	s.mu.RUnlock()
	if !bound {
		return DeviceMaterial{}, deviceMaterialMissingf("account %q has no device binding", accountID)
	}
	if cached {
		return cloneDeviceMaterial(material), nil
	}
	opened, err := s.openDeviceMaterial(recID)
	if err != nil {
		return DeviceMaterial{}, deviceMaterialMissingf("device %q material is missing or corrupt", recID)
	}
	s.mu.Lock()
	s.deviceMaterial[recID] = cloneDeviceMaterial(opened)
	s.mu.Unlock()
	return opened, nil
}

// MarkDeviceSeen records a successful vendor login: first/last seen, the login
// counter and the canonical username alias. Counters are best effort and never
// affect identity stability.
func (s *Store) MarkDeviceSeen(accountID, username string) (DeviceRecord, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.accountIndexLocked(accountID) < 0 {
		return DeviceRecord{}, notFoundf("account %q not found", accountID)
	}
	recID, ok := s.deviceBindings[accountID]
	if !ok {
		return DeviceRecord{}, deviceNotFoundf("account %q has no device binding", accountID)
	}
	rec := s.deviceRecordLocked(recID)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", recID)
	}
	s.markDeviceSeenLocked(accountID, username)
	return cloneDeviceRecord(*rec), nil
}

// markDeviceSeenLocked updates the bound record. The caller holds the write
// lock (MarkLogin calls it for a successful vendor login).
func (s *Store) markDeviceSeenLocked(accountID, username string) {
	recID, ok := s.deviceBindings[accountID]
	if !ok {
		return
	}
	rec := s.deviceRecordLocked(recID)
	if rec == nil {
		return
	}
	now := iso(s.now())
	if rec.FirstSeenAt == nil {
		rec.FirstSeenAt = &now
	}
	rec.LastSeenAt = &now
	rec.LoginCount++
	username = strings.TrimSpace(username)
	if username == "" {
		return
	}
	exact := deviceAccountKey(rec.Platform, username)
	lower := deviceAccountKey(rec.Platform, strings.ToLower(username))
	if rec.AccountKey == "" {
		rec.AccountKey = exact
	}
	rec.AccountKeyAliases = appendDeviceAlias(rec.AccountKeyAliases, exact)
	rec.AccountKeyAliases = appendDeviceAlias(rec.AccountKeyAliases, lower)
}

// --- migration, reconciliation and GC ---

// MigrateDevices converts the legacy plaintext device map into pool records.
// It is deterministic and idempotent; it is also run automatically by Restore
// before a v1 document is installed.
func (s *Store) MigrateDevices() error {
	if s.deviceSealer == nil || len(s.devicePool) > 0 || len(s.devices) == 0 {
		return nil
	}
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.Lock()
	defer s.mu.Unlock()
	if len(s.devicePool) > 0 {
		return invalidf("state has both a device pool and a legacy device map")
	}
	records, bindings, materials, err := buildLegacyPool(s.accounts, s.devices, s.sealDeviceMaterial, s.now())
	if err != nil {
		return err
	}
	for _, rec := range records {
		copy := rec
		s.devicePool[copy.ID] = &copy
	}
	for id, material := range materials {
		s.deviceMaterial[id] = cloneDeviceMaterial(material)
	}
	s.deviceBindings = bindings
	s.devices = make(map[string]DeviceIdentity, len(bindings))
	for accountID, deviceID := range bindings {
		if material, ok := s.deviceMaterial[deviceID]; ok {
			s.devices[accountID] = material.Identity
		}
	}
	s.addAuditLocked(model.SeverityInfo, "system", "device.migrated", "pool",
		fmt.Sprintf("from=snapshot_v1 count=%d", len(records)))
	return nil
}

// buildLegacyPool converts plaintext identities to deterministic pool records.
// It seals every material through seal before returning, so a failure leaves
// no half-written state.
func buildLegacyPool(
	accounts []model.Account,
	devices map[string]DeviceIdentity,
	seal func(DeviceMaterial) error,
	now time.Time,
) ([]DeviceRecord, map[string]string, map[string]DeviceMaterial, error) {
	byID := make(map[string]model.Account, len(accounts))
	for _, account := range accounts {
		byID[account.ID] = account
	}
	accountIDs := make([]string, 0, len(devices))
	for accountID := range devices {
		accountIDs = append(accountIDs, accountID)
	}
	sort.Strings(accountIDs)

	taken := make(map[string]bool, len(devices))
	records := make([]DeviceRecord, 0, len(devices))
	bindings := make(map[string]string, len(devices))
	materials := make(map[string]DeviceMaterial, len(devices))
	for _, accountID := range accountIDs {
		account, ok := byID[accountID]
		if !ok {
			return nil, nil, nil, invalidf("legacy device for unknown account %q", accountID)
		}
		identity := devices[accountID]
		if !identity.valid() {
			return nil, nil, nil, invalidf("legacy device for account %q is incomplete", accountID)
		}
		family, err := familyOf(identity, account.Platform)
		if err != nil {
			return nil, nil, nil, err
		}
		deviceID := legacyDeviceID(accountID, identity.UID, taken)
		machine := legacyMachineCode(accountID, identity)
		profile := profileForVersion(identity.Version)
		presented := account.LastLoginAt
		if !validRFC3339(presented) {
			presented = iso(now)
		}
		key := deviceAccountKey(family, account.Username)
		rec := DeviceRecord{
			ID: deviceID, State: DeviceAssigned, Platform: family, Profile: profile,
			Algorithm: DeviceAlgorithmLegacy, Fingerprint: deviceFingerprint(machine, identity),
			Hashes: deviceHashes(identity, machine), Claims: deviceClaims(identity),
			AccountKey: key, AccountKeyAliases: appendDeviceAlias(nil, deviceAccountKey(family, strings.ToLower(account.Username))),
			AssignedAccountID: accountID, AssignedAt: &presented, PresentedAt: &presented,
			CreatedAt: iso(now), CreatedBy: "system",
			History: []DeviceEvent{{At: iso(now), Action: "migrated", Actor: "system", Detail: "from snapshot v1"}},
		}
		material := DeviceMaterial{
			DeviceID: deviceID, MachineCode: machine, Identity: identity,
			Platform: family, Profile: profile, Algorithm: DeviceAlgorithmLegacy,
			Fingerprint: rec.Fingerprint, CreatedAt: rec.CreatedAt, PresentedAt: &presented,
			AccountKey: key, AccountKeyAliases: rec.AccountKeyAliases,
		}
		if err := seal(material); err != nil {
			return nil, nil, nil, err
		}
		records = append(records, rec)
		bindings[accountID] = deviceID
		materials[deviceID] = material
	}
	return records, bindings, materials, nil
}

func legacyDeviceID(accountID, uid string, taken map[string]bool) string {
	for counter := 0; ; counter++ {
		material := "legacy|" + accountID + "|" + uid
		if counter > 0 {
			material += "|" + strconv.Itoa(counter)
		}
		sum := sha256.Sum256([]byte(material))
		id := DeviceIDPrefix + hex.EncodeToString(sum[:])[:16]
		if !taken[id] {
			taken[id] = true
			return id
		}
	}
}

func legacyMachineCode(accountID string, identity DeviceIdentity) string {
	sum := sha256.Sum256([]byte("ajs.device.legacy.v1\x1f" + accountID + "\x1f" + identity.UID + "\x1f" + identity.OSDID))
	return hex.EncodeToString(sum[:])
}

func validRFC3339(value string) bool {
	if value == "" {
		return false
	}
	_, err := time.Parse(time.RFC3339, value)
	return err == nil
}

// ReconcileDeviceMaterials opens every sealed record, verifies it against the
// index, recovers orphans as retired records and rebuilds the account mirror.
// A missing or corrupt entry degrades that record (login fails closed); it
// never fails the load.
func (s *Store) ReconcileDeviceMaterials() error {
	if s.deviceSealer == nil {
		return nil
	}
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()

	s.mu.RLock()
	records := make([]DeviceRecord, 0, len(s.devicePool))
	for _, rec := range s.devicePool {
		records = append(records, cloneDeviceRecord(*rec))
	}
	s.mu.RUnlock()

	materials := make(map[string]DeviceMaterial, len(records))
	missing := make([]DeviceRecord, 0)
	dropped := make([]string, 0)
	for _, rec := range records {
		material, err := s.openDeviceMaterial(rec.ID)
		if err != nil || material.Fingerprint != rec.Fingerprint {
			// A crash between the two GC deletes leaves a retired, unbound
			// record without material. Drop it: it can never be restored and
			// must not resurrect. Any other record degrades in place.
			if rec.State == DeviceRetired && rec.AssignedAccountID == "" {
				dropped = append(dropped, rec.ID)
				continue
			}
			missing = append(missing, rec)
			continue
		}
		materials[rec.ID] = material
	}

	// Sealed entries without an index row are crash leftovers: recover them as
	// retired records, never as silently assigned identities.
	now := s.now()
	nowStamp := iso(now)
	existing := make(map[string]bool, len(records))
	for _, rec := range records {
		existing[rec.ID] = true
	}
	var recovered []DeviceRecord
	for _, id := range s.deviceSealer.IDs() {
		if existing[id] {
			continue
		}
		material, err := s.openDeviceMaterial(id)
		if err != nil {
			continue
		}
		presented := material.PresentedAt
		if presented == nil {
			presented = &nowStamp
		}
		created := material.CreatedAt
		if created == "" {
			created = nowStamp
		}
		rec := DeviceRecord{
			ID: id, State: DeviceRetired, Platform: material.Platform, Profile: material.Profile,
			Algorithm: material.Algorithm, Fingerprint: material.Fingerprint,
			Hashes: deviceHashes(material.Identity, material.MachineCode), Claims: deviceClaims(material.Identity),
			AccountKey: material.AccountKey, AccountKeyAliases: append([]string(nil), material.AccountKeyAliases...),
			PresentedAt: presented, CreatedAt: created, CreatedBy: "system",
			RetiredAt: &nowStamp, RetiredReason: "recovered",
			History: []DeviceEvent{{At: nowStamp, Action: "recovered", Actor: "system", Detail: "source=sealed_file"}},
		}
		recovered = append(recovered, rec)
		materials[id] = material
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	s.deviceMaterial = materials
	for _, id := range dropped {
		delete(s.devicePool, id)
	}
	for i := range recovered {
		rec := recovered[i]
		s.devicePool[rec.ID] = &rec
		s.addAuditLocked(model.SeverityWarn, "system", "device.recovered", rec.ID, "source=sealed_file")
	}
	mirror := make(map[string]DeviceIdentity, len(s.deviceBindings))
	for accountID, deviceID := range s.deviceBindings {
		if material, ok := s.deviceMaterial[deviceID]; ok {
			mirror[accountID] = material.Identity
		}
	}
	s.devices = mirror
	s.deviceWarnings = nil
	if len(dropped) > 0 {
		s.deviceWarnings = append(s.deviceWarnings,
			fmt.Sprintf("%d retired records were dropped because their material is gone", len(dropped)))
	}
	if len(missing) > 0 {
		s.deviceWarnings = append(s.deviceWarnings,
			fmt.Sprintf("%d device records have no material (restore from export)", len(missing)))
		for i, rec := range missing {
			if i >= 20 {
				break
			}
			s.addAuditLocked(model.SeverityError, "system", "device.material_missing", rec.ID,
				"account="+s.deviceAccountLabelLocked(rec.AssignedAccountID))
		}
	}
	return nil
}

// GCDevices removes retired, unassigned records past retention. retentionDays
// < 0 selects the configured window; 0 keeps records forever. It deletes the
// sealed entry before the index row, so a crash never leaves a record without
// material.
func (s *Store) GCDevices(now time.Time, retentionDays int) (int, error) {
	if s.deviceSealer == nil {
		return 0, nil
	}
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	if retentionDays < 0 {
		s.mu.RLock()
		retentionDays = s.deviceCfg.RetentionDays
		s.mu.RUnlock()
	}
	if retentionDays <= 0 {
		return 0, nil
	}
	s.mu.RLock()
	var candidates []DeviceRecord
	for _, rec := range s.devicePool {
		if rec.State != DeviceRetired || rec.AssignedAccountID != "" {
			continue
		}
		if deviceExpired(*rec, now, retentionDays) {
			candidates = append(candidates, cloneDeviceRecord(*rec))
		}
	}
	s.mu.RUnlock()
	sort.Slice(candidates, func(i, j int) bool { return candidates[i].ID < candidates[j].ID })
	oldest, newest := "", ""
	var oldestAt, newestAt string
	for _, rec := range candidates {
		if rec.RetiredAt == nil {
			continue
		}
		prefix := shortDeviceFingerprint(rec.Fingerprint)
		if oldestAt == "" || *rec.RetiredAt < oldestAt {
			oldestAt, oldest = *rec.RetiredAt, prefix
		}
		if newestAt == "" || *rec.RetiredAt > newestAt {
			newestAt, newest = *rec.RetiredAt, prefix
		}
	}

	removed := 0
	var firstErr error
	for _, rec := range candidates {
		if err := s.deleteDeviceMaterial(rec.ID); err != nil {
			if firstErr == nil {
				firstErr = err
			}
			continue
		}
		s.mu.Lock()
		current := s.deviceRecordLocked(rec.ID)
		if current != nil && current.State == DeviceRetired && current.AssignedAccountID == "" {
			delete(s.devicePool, rec.ID)
			delete(s.deviceMaterial, rec.ID)
			removed++
		}
		s.mu.Unlock()
	}
	if removed > 0 {
		s.mu.Lock()
		s.addAuditLocked(model.SeverityInfo, "system", "device.gc", "pool",
			fmt.Sprintf("removed=%d retention_days=%d oldest=%s newest=%s",
				removed, retentionDays, oldest, newest))
		s.mu.Unlock()
	}
	return removed, firstErr
}

// shortDeviceFingerprint is the audit-safe prefix of a fingerprint.
func shortDeviceFingerprint(fingerprint string) string {
	fingerprint = strings.TrimPrefix(fingerprint, "sha256:")
	if len(fingerprint) > 8 {
		fingerprint = fingerprint[:8]
	}
	return fingerprint
}

// --- export / import ---

// DeviceExportEnvelope is the only device-pool representation that leaves the
// daemon. The header is authenticated as AES-GCM additional data.
type DeviceExportEnvelope struct {
	Format        string               `json:"format"`
	Version       int                  `json:"version"`
	CreatedAt     string               `json:"createdAt"`
	KDF           DeviceEnvelopeKDF    `json:"kdf"`
	Cipher        DeviceEnvelopeCipher `json:"cipher"`
	PayloadSHA256 string               `json:"payloadSha256"`
	Ciphertext    string               `json:"ciphertext"`
	DeviceCount   int                  `json:"deviceCount"`
}

// DeviceEnvelopeKDF is the passphrase KDF header.
type DeviceEnvelopeKDF struct {
	Name       string `json:"name"`
	Iterations int    `json:"iterations"`
	Salt       string `json:"salt"`
}

// DeviceEnvelopeCipher is the cipher header.
type DeviceEnvelopeCipher struct {
	Name  string `json:"name"`
	Nonce string `json:"nonce"`
}

// DeviceExportSource identifies the writer of a payload.
type DeviceExportSource struct {
	DaemonVersion string `json:"daemonVersion,omitempty"`
	StateSchema   int    `json:"stateSchema"`
}

// DeviceExportPayload is the encrypted plaintext.
type DeviceExportPayload struct {
	Format     string               `json:"format"`
	Version    int                  `json:"version"`
	ExportedAt string               `json:"exportedAt"`
	Source     DeviceExportSource   `json:"source"`
	Devices    []DeviceExportDevice `json:"devices"`
}

// DeviceExportDevice carries the full identity. It exists only inside the
// encrypted payload.
type DeviceExportDevice struct {
	DeviceID          string         `json:"deviceId"`
	Label             string         `json:"label,omitempty"`
	Platform          model.Platform `json:"platform"`
	Profile           string         `json:"profile"`
	Algorithm         string         `json:"algorithm"`
	MachineCode       string         `json:"machineCode"`
	Identity          DeviceIdentity `json:"identity"`
	Fingerprint       string         `json:"fingerprint"`
	AccountKey        string         `json:"accountKey,omitempty"`
	AccountKeyAliases []string       `json:"accountKeyAliases,omitempty"`
	CreatedAt         string         `json:"createdAt"`
	PresentedAt       *string        `json:"presentedAt,omitempty"`
	FirstSeenAt       *string        `json:"firstSeenAt,omitempty"`
	LastSeenAt        *string        `json:"lastSeenAt,omitempty"`
	LoginCount        int            `json:"loginCount"`
}

// DeviceExportOptions selects records. ExcludeAccountKeys and ExcludeLabels
// default to false: the envelope is encrypted, so labels and keys travel
// unless the operator opts out.
type DeviceExportOptions struct {
	Scope              string
	DeviceIDs          []string
	ExcludeAccountKeys bool
	ExcludeLabels      bool
	Passphrase         string
}

func validateDevicePassphrase(passphrase string) error {
	if len(passphrase) < devicePassphraseMin || len(passphrase) > devicePassphraseMax {
		return invalidf("device passphrase must be between %d and %d bytes",
			devicePassphraseMin, devicePassphraseMax)
	}
	return nil
}

// ExportDevicePool builds the passphrase-encrypted envelope. It never writes
// raw values anywhere except the ciphertext.
func (s *Store) ExportDevicePool(opts DeviceExportOptions) (DeviceExportEnvelope, error) {
	if s.deviceSealer == nil {
		return DeviceExportEnvelope{}, devicePoolDisabled()
	}
	if err := validateDevicePassphrase(opts.Passphrase); err != nil {
		return DeviceExportEnvelope{}, err
	}
	// Serialise with GC/purge so a selected record's material cannot be
	// deleted between selection and open.
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	scope := strings.TrimSpace(opts.Scope)
	if scope == "" {
		scope = "assigned"
	}
	switch scope {
	case "assigned", "retired", "all":
	default:
		return DeviceExportEnvelope{}, deviceInvalidf(DeviceReasonExportFormat,
			"export scope must be assigned, retired or all")
	}

	records, err := s.selectExportRecords(scope, opts.DeviceIDs)
	if err != nil {
		return DeviceExportEnvelope{}, err
	}
	if len(records) == 0 {
		return DeviceExportEnvelope{}, deviceConflictf(DeviceReasonExportEmpty, "device export selection is empty")
	}
	if len(records) > DeviceExportMaxDevices {
		return DeviceExportEnvelope{}, deviceInvalidf(DeviceReasonExportFormat,
			"device export is limited to %d records", DeviceExportMaxDevices)
	}

	payload := DeviceExportPayload{
		Format:     DevicePayloadFormat,
		Version:    DevicePayloadVersion,
		ExportedAt: iso(s.now()),
		Source:     DeviceExportSource{StateSchema: SnapshotVersion},
		Devices:    make([]DeviceExportDevice, 0, len(records)),
	}
	for _, rec := range records {
		material, err := s.exportMaterial(rec)
		if err != nil {
			return DeviceExportEnvelope{}, err
		}
		entry := DeviceExportDevice{
			DeviceID: rec.ID, Platform: rec.Platform, Profile: rec.Profile,
			Algorithm: rec.Algorithm, MachineCode: material.MachineCode,
			Identity: material.Identity, Fingerprint: rec.Fingerprint,
			CreatedAt: rec.CreatedAt, PresentedAt: cloneStringPtr(rec.PresentedAt),
			FirstSeenAt: cloneStringPtr(rec.FirstSeenAt), LastSeenAt: cloneStringPtr(rec.LastSeenAt),
			LoginCount: rec.LoginCount,
		}
		if !opts.ExcludeLabels {
			entry.Label = rec.Label
		}
		if !opts.ExcludeAccountKeys {
			entry.AccountKey = rec.AccountKey
			entry.AccountKeyAliases = append([]string(nil), rec.AccountKeyAliases...)
		}
		payload.Devices = append(payload.Devices, entry)
	}

	plaintext, err := json.Marshal(payload)
	if err != nil {
		return DeviceExportEnvelope{}, fmt.Errorf("store: encode device payload: %w", err)
	}
	payloadSum := sha256.Sum256(plaintext)
	envelope := DeviceExportEnvelope{
		Format:        DeviceFormat,
		Version:       DeviceFormatVersion,
		CreatedAt:     iso(s.now()),
		KDF:           DeviceEnvelopeKDF{Name: deviceKDFName, Iterations: deviceKDFIterations},
		Cipher:        DeviceEnvelopeCipher{Name: deviceCipherName},
		PayloadSHA256: hex.EncodeToString(payloadSum[:]),
		DeviceCount:   len(payload.Devices),
	}
	salt := make([]byte, deviceSaltSize)
	if _, err := rand.Read(salt); err != nil {
		return DeviceExportEnvelope{}, fmt.Errorf("store: export salt: %w", err)
	}
	nonce := make([]byte, deviceNonceSize)
	if _, err := rand.Read(nonce); err != nil {
		return DeviceExportEnvelope{}, fmt.Errorf("store: export nonce: %w", err)
	}
	envelope.KDF.Salt = base64.StdEncoding.EncodeToString(salt)
	envelope.Cipher.Nonce = base64.StdEncoding.EncodeToString(nonce)
	key, err := pbkdf2.Key(sha256.New, opts.Passphrase, salt, deviceKDFIterations, 32)
	if err != nil {
		return DeviceExportEnvelope{}, fmt.Errorf("store: export key: %w", err)
	}
	aead, err := newDeviceAEAD(key)
	if err != nil {
		return DeviceExportEnvelope{}, err
	}
	ciphertext := aead.Seal(nil, nonce, plaintext, []byte(deviceEnvelopeAAD(envelope)))
	envelope.Ciphertext = base64.StdEncoding.EncodeToString(ciphertext)

	s.mu.Lock()
	s.addAuditLocked(model.SeverityInfo, "operator", "device.export", "pool",
		fmt.Sprintf("count=%d scope=%s sha256=%s", len(payload.Devices), scope, envelope.PayloadSHA256[:16]))
	s.mu.Unlock()
	return envelope, nil
}

// selectExportRecords applies scope and explicit ids. Quarantined records
// never leave the daemon.
func (s *Store) selectExportRecords(scope string, ids []string) ([]DeviceRecord, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	if len(ids) > 0 {
		seen := make(map[string]bool, len(ids))
		out := make([]DeviceRecord, 0, len(ids))
		for _, id := range ids {
			if seen[id] {
				continue
			}
			seen[id] = true
			rec := s.deviceRecordLocked(id)
			if rec == nil {
				return nil, deviceNotFoundf("device %q not found", id)
			}
			if rec.State == DeviceQuarantined {
				return nil, deviceConflictf(DeviceReasonStateInvalid,
					"device %q is quarantined and cannot be exported", id)
			}
			out = append(out, cloneDeviceRecord(*rec))
		}
		return out, nil
	}
	out := make([]DeviceRecord, 0, len(s.devicePool))
	for _, rec := range s.devicePool {
		if rec.State == DeviceQuarantined {
			continue
		}
		switch scope {
		case "assigned":
			if rec.State != DeviceAssigned {
				continue
			}
		case "retired":
			if rec.State != DeviceRetired {
				continue
			}
		case "all":
			// every non-quarantined record
		}
		out = append(out, cloneDeviceRecord(*rec))
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

func (s *Store) exportMaterial(rec DeviceRecord) (DeviceMaterial, error) {
	s.mu.RLock()
	material, cached := s.deviceMaterial[rec.ID]
	s.mu.RUnlock()
	if cached {
		return cloneDeviceMaterial(material), nil
	}
	opened, err := s.openDeviceMaterial(rec.ID)
	if err != nil {
		return DeviceMaterial{}, deviceMaterialMissingf("device %q material is missing or corrupt", rec.ID)
	}
	if opened.Fingerprint != rec.Fingerprint {
		return DeviceMaterial{}, deviceMaterialMissingf("device %q material fingerprint does not match the record", rec.ID)
	}
	return opened, nil
}

func newDeviceAEAD(key []byte) (cipher.AEAD, error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("store: device envelope cipher: %w", err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("store: device envelope gcm: %w", err)
	}
	return aead, nil
}

func deviceEnvelopeAAD(env DeviceExportEnvelope) string {
	return env.Format + "\x1f" + strconv.Itoa(env.Version) + "\x1f" +
		env.KDF.Name + "\x1f" + strconv.Itoa(env.KDF.Iterations) + "\x1f" +
		env.KDF.Salt + "\x1f" + env.Cipher.Name + "\x1f" + env.Cipher.Nonce + "\x1f" +
		env.PayloadSHA256 + "\x1f" + strconv.Itoa(env.DeviceCount)
}

// DeviceImportOptions controls ImportDevicePool.
type DeviceImportOptions struct {
	Passphrase string
	DryRun     bool
	Bind       bool
}

// DeviceImportConflict is one all-or-nothing import conflict.
type DeviceImportConflict struct {
	DeviceID            string `json:"deviceId"`
	ExistingFingerprint string `json:"existingFingerprint"`
	ImportedFingerprint string `json:"importedFingerprint"`
	Reason              string `json:"reason"`
}

// DeviceImportConflictError reports conflicts; no record was mutated.
type DeviceImportConflictError struct {
	Conflicts []DeviceImportConflict
}

func (e *DeviceImportConflictError) Error() string {
	return fmt.Sprintf("device import has %d conflicts", len(e.Conflicts))
}

// Unwrap maps the conflict to the store's 409 kind.
func (e *DeviceImportConflictError) Unwrap() error { return ErrConflict }

// DeviceReason implements the stable reason interface.
func (e *DeviceImportConflictError) DeviceReason() string { return DeviceReasonImportConflict }

// DeviceBindingConflict reports an imported record that could not be bound.
type DeviceBindingConflict struct {
	DeviceID  string `json:"deviceId"`
	AccountID string `json:"accountId,omitempty"`
	Reason    string `json:"reason"`
}

// DeviceImportDevice is one per-record import outcome.
type DeviceImportDevice struct {
	DeviceID    string      `json:"deviceId"`
	State       DeviceState `json:"state"`
	Fingerprint string      `json:"fingerprint"`
	Action      string      `json:"action"`
}

// DeviceImportResult is the dry-run and commit summary.
type DeviceImportResult struct {
	DryRun           bool                    `json:"dryRun"`
	Format           string                  `json:"format"`
	Version          int                     `json:"version"`
	Added            int                     `json:"added"`
	Skipped          int                     `json:"skipped"`
	Conflicts        int                     `json:"conflicts"`
	Bound            int                     `json:"bound"`
	Devices          []DeviceImportDevice    `json:"devices"`
	BindingConflicts []DeviceBindingConflict `json:"bindingConflicts"`
	Warnings         []string                `json:"warnings"`
}

func decodeStrictDeviceJSON(data []byte, out any) error {
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(out); err != nil {
		return err
	}
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		return errors.New("trailing data after JSON document")
	}
	return nil
}

// ImportDevicePool decrypts, validates, conflict-checks and (unless dryRun)
// commits an envelope. It is idempotent: re-importing the same envelope skips
// every record. Any decrypt, format or conflict error leaves the pool
// untouched.
func (s *Store) ImportDevicePool(data []byte, opts DeviceImportOptions) (DeviceImportResult, error) {
	if s.deviceSealer == nil {
		return DeviceImportResult{}, devicePoolDisabled()
	}
	if err := validateDevicePassphrase(opts.Passphrase); err != nil {
		return DeviceImportResult{}, err
	}
	if len(data) == 0 || len(data) > DeviceImportMaxBytes {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat,
			"device import must be between 1 and %d bytes", DeviceImportMaxBytes)
	}

	var envelope DeviceExportEnvelope
	if err := decodeStrictDeviceJSON(data, &envelope); err != nil {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import envelope is malformed")
	}
	if envelope.Format != DeviceFormat || envelope.Version != DeviceFormatVersion {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat,
			"device import envelope format or version is unsupported")
	}
	if envelope.KDF.Name != deviceKDFName || envelope.KDF.Iterations != deviceKDFIterations {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import KDF is unsupported")
	}
	if envelope.Cipher.Name != deviceCipherName {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import cipher is unsupported")
	}
	salt, err := base64.StdEncoding.DecodeString(envelope.KDF.Salt)
	if err != nil || len(salt) != deviceSaltSize {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import salt is malformed")
	}
	nonce, err := base64.StdEncoding.DecodeString(envelope.Cipher.Nonce)
	if err != nil || len(nonce) != deviceNonceSize {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import nonce is malformed")
	}
	ciphertext, err := base64.StdEncoding.DecodeString(envelope.Ciphertext)
	if err != nil || len(ciphertext) == 0 {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import ciphertext is malformed")
	}
	if envelope.DeviceCount < 0 || envelope.DeviceCount > DeviceExportMaxDevices {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import count is invalid")
	}

	key, err := pbkdf2.Key(sha256.New, opts.Passphrase, salt, deviceKDFIterations, 32)
	if err != nil {
		return DeviceImportResult{}, fmt.Errorf("store: import key: %w", err)
	}
	aead, err := newDeviceAEAD(key)
	if err != nil {
		return DeviceImportResult{}, err
	}
	plaintext, err := aead.Open(nil, nonce, ciphertext, []byte(deviceEnvelopeAAD(envelope)))
	if err != nil {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportDecrypt, "device import could not be decrypted")
	}
	sum := sha256.Sum256(plaintext)
	if hex.EncodeToString(sum[:]) != envelope.PayloadSHA256 {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import payload checksum does not match")
	}

	var payload DeviceExportPayload
	if err := decodeStrictDeviceJSON(plaintext, &payload); err != nil {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import payload is malformed")
	}
	if payload.Format != DevicePayloadFormat || payload.Version != DevicePayloadVersion {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import payload format is unsupported")
	}
	if len(payload.Devices) == 0 || len(payload.Devices) > DeviceExportMaxDevices {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import payload has an invalid record count")
	}
	if envelope.DeviceCount != len(payload.Devices) {
		return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat, "device import count does not match the payload")
	}

	planned := make([]DeviceImportDevice, 0, len(payload.Devices))
	materials := make(map[string]DeviceMaterial, len(payload.Devices))
	seenIDs := make(map[string]bool, len(payload.Devices))
	seenFingerprints := make(map[string]bool, len(payload.Devices))
	for _, device := range payload.Devices {
		_, material, err := validateImportDevice(device)
		if err != nil {
			return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat,
				"device %q is invalid: %s", device.DeviceID, err.Error())
		}
		if seenIDs[device.DeviceID] {
			return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat,
				"device import payload repeats %q", device.DeviceID)
		}
		if seenFingerprints[material.Fingerprint] {
			return DeviceImportResult{}, deviceInvalidf(DeviceReasonImportFormat,
				"device import payload repeats a fingerprint")
		}
		seenIDs[device.DeviceID] = true
		seenFingerprints[material.Fingerprint] = true
		materials[device.DeviceID] = material
		state := DeviceAvailable
		if device.PresentedAt != nil {
			state = DeviceRetired
		}
		planned = append(planned, DeviceImportDevice{
			DeviceID: device.DeviceID, State: state,
			Fingerprint: material.Fingerprint, Action: "added",
		})
	}

	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()

	s.mu.RLock()
	var conflicts []DeviceImportConflict
	for i := range planned {
		existing := s.deviceRecordLocked(planned[i].DeviceID)
		if existing == nil {
			for _, rec := range s.devicePool {
				if rec.Fingerprint == materials[planned[i].DeviceID].Fingerprint {
					conflicts = append(conflicts, DeviceImportConflict{
						DeviceID: planned[i].DeviceID, ExistingFingerprint: rec.Fingerprint,
						ImportedFingerprint: materials[planned[i].DeviceID].Fingerprint,
						Reason:              "duplicate_identity",
					})
					break
				}
			}
			continue
		}
		if existing.Fingerprint != materials[planned[i].DeviceID].Fingerprint {
			conflicts = append(conflicts, DeviceImportConflict{
				DeviceID: planned[i].DeviceID, ExistingFingerprint: existing.Fingerprint,
				ImportedFingerprint: materials[planned[i].DeviceID].Fingerprint,
				Reason:              "fingerprint_mismatch",
			})
			continue
		}
		planned[i].Action = "skipped"
		planned[i].State = existing.State
	}
	s.mu.RUnlock()
	if len(conflicts) > 0 {
		return DeviceImportResult{Conflicts: len(conflicts), Devices: planned}, &DeviceImportConflictError{Conflicts: conflicts}
	}

	// Binding plan: exactly one local account match, no existing binding.
	bindings := make(map[string]string)
	var bindingConflicts []DeviceBindingConflict
	var warnings []string
	if opts.Bind {
		s.mu.RLock()
		for _, device := range payload.Devices {
			plan := findImportPlan(planned, device.DeviceID)
			if plan == nil {
				continue
			}
			if plan.Action == "skipped" {
				live := s.deviceRecordLocked(device.DeviceID)
				if live == nil || (live.State != DeviceAvailable && live.State != DeviceRetired) {
					bindingConflicts = append(bindingConflicts, DeviceBindingConflict{
						DeviceID: device.DeviceID, Reason: "record_assigned",
					})
					continue
				}
			}
			keys := importAccountKeys(device)
			if len(keys) == 0 {
				continue
			}
			var matches []model.Account
			for _, account := range s.accounts {
				if importAccountMatches(keys, device.Platform, account) {
					matches = append(matches, account)
				}
			}
			switch {
			case len(matches) == 0:
				continue
			case len(matches) > 1:
				bindingConflicts = append(bindingConflicts, DeviceBindingConflict{
					DeviceID: device.DeviceID, Reason: "multiple_matches",
				})
			case s.deviceBindings[matches[0].ID] != "":
				bindingConflicts = append(bindingConflicts, DeviceBindingConflict{
					DeviceID: device.DeviceID, AccountID: matches[0].ID, Reason: "already_bound",
				})
			default:
				bindings[device.DeviceID] = matches[0].ID
			}
		}
		s.mu.RUnlock()
	}
	available := 0
	for _, device := range payload.Devices {
		if device.PresentedAt == nil {
			available++
		}
	}
	if available > 0 {
		warnings = append(warnings, fmt.Sprintf(
			"%d identities have never been presented to the vendor and are available", available))
	}

	result := DeviceImportResult{
		DryRun: opts.DryRun, Format: envelope.Format, Version: envelope.Version,
		Devices: planned, BindingConflicts: bindingConflicts, Warnings: warnings,
	}
	if result.BindingConflicts == nil {
		result.BindingConflicts = []DeviceBindingConflict{}
	}
	if result.Warnings == nil {
		result.Warnings = []string{}
	}
	for _, plan := range planned {
		if plan.Action == "added" {
			result.Added++
		} else {
			result.Skipped++
		}
	}
	result.Bound = len(bindings)
	if opts.DryRun {
		return result, nil
	}

	// Seal every new material first; roll back the batch on failure.
	sealedIDs := make([]string, 0, result.Added)
	now := iso(s.now())
	for _, device := range payload.Devices {
		plan := findImportPlan(planned, device.DeviceID)
		if plan == nil || plan.Action != "added" {
			continue
		}
		material := materials[device.DeviceID]
		material.CreatedAt = device.CreatedAt
		if material.CreatedAt == "" {
			material.CreatedAt = now
		}
		material.PresentedAt = cloneStringPtr(device.PresentedAt)
		if err := s.sealDeviceMaterial(material); err != nil {
			s.rollbackDeviceSeals(sealedIDs)
			return DeviceImportResult{}, err
		}
		sealedIDs = append(sealedIDs, device.DeviceID)
	}

	s.mu.Lock()
	// Re-check the conflict set under the write lock (no other pool writer can
	// run while deviceMu is held, but a restored store may have changed).
	for _, plan := range planned {
		if plan.Action != "added" {
			continue
		}
		if existing := s.deviceRecordLocked(plan.DeviceID); existing != nil {
			s.mu.Unlock()
			s.rollbackDeviceSeals(sealedIDs)
			return DeviceImportResult{}, &DeviceImportConflictError{Conflicts: []DeviceImportConflict{{
				DeviceID: plan.DeviceID, ExistingFingerprint: existing.Fingerprint,
				ImportedFingerprint: plan.Fingerprint, Reason: "fingerprint_mismatch",
			}}}
		}
	}
	for _, device := range payload.Devices {
		plan := findImportPlan(planned, device.DeviceID)
		if plan == nil {
			continue
		}
		if plan.Action == "skipped" {
			accountID, ok := bindings[device.DeviceID]
			if !ok {
				continue
			}
			rec := s.deviceRecordLocked(device.DeviceID)
			if rec == nil || (rec.State != DeviceAvailable && rec.State != DeviceRetired) {
				continue
			}
			rec.State = DeviceAssigned
			rec.AssignedAccountID = accountID
			rec.AssignedAt = &now
			rec.RetiredAt = nil
			rec.RetiredReason = ""
			s.deviceBindings[accountID] = rec.ID
			s.devices[accountID] = materials[device.DeviceID].Identity
			s.deviceAppendEventLocked(rec, "assigned", "operator", "source=import")
			continue
		}
		if plan.Action != "added" {
			continue
		}
		material := materials[device.DeviceID]
		rec := DeviceRecord{
			ID: device.DeviceID, Label: device.Label, State: plan.State,
			Platform: device.Platform, Profile: device.Profile, Algorithm: device.Algorithm,
			Fingerprint: material.Fingerprint,
			Hashes:      deviceHashes(material.Identity, material.MachineCode),
			Claims:      deviceClaims(material.Identity),
			AccountKey:  device.AccountKey, AccountKeyAliases: append([]string(nil), device.AccountKeyAliases...),
			PresentedAt: cloneStringPtr(device.PresentedAt),
			FirstSeenAt: cloneStringPtr(device.FirstSeenAt), LastSeenAt: cloneStringPtr(device.LastSeenAt),
			LoginCount: device.LoginCount, CreatedAt: material.CreatedAt, CreatedBy: "import",
			History: []DeviceEvent{{At: now, Action: "imported", Actor: "operator", Detail: "from envelope"}},
		}
		if rec.State == DeviceRetired {
			rec.RetiredAt = &now
			rec.RetiredReason = "imported"
		}
		if accountID, ok := bindings[device.DeviceID]; ok {
			rec.State = DeviceAssigned
			rec.AssignedAccountID = accountID
			rec.AssignedAt = &now
			rec.RetiredAt = nil
			rec.RetiredReason = ""
			s.deviceBindings[accountID] = rec.ID
			s.devices[accountID] = material.Identity
			s.deviceAppendEventLocked(&rec, "assigned", "operator", "source=import")
		}
		s.devicePool[rec.ID] = &rec
		s.deviceMaterial[rec.ID] = cloneDeviceMaterial(material)
	}
	result.Bound = len(bindings)
	s.addAuditLocked(model.SeverityInfo, "operator", "device.import", "pool",
		fmt.Sprintf("added=%d skipped=%d bound=%d conflicts=%d dryRun=false sha256=%s",
			result.Added, result.Skipped, result.Bound, result.Conflicts, envelope.PayloadSHA256[:16]))
	s.mu.Unlock()
	return result, nil
}

func findImportPlan(plans []DeviceImportDevice, deviceID string) *DeviceImportDevice {
	for i := range plans {
		if plans[i].DeviceID == deviceID {
			return &plans[i]
		}
	}
	return nil
}

func importAccountKeys(device DeviceExportDevice) []string {
	keys := make([]string, 0, len(device.AccountKeyAliases)+1)
	if device.AccountKey != "" {
		keys = append(keys, device.AccountKey)
	}
	for _, alias := range device.AccountKeyAliases {
		if alias != "" {
			keys = append(keys, alias)
		}
	}
	return keys
}

func importAccountMatches(keys []string, family model.Platform, account model.Account) bool {
	candidates := []string{
		deviceAccountKey(family, account.Username),
		deviceAccountKey(family, strings.ToLower(account.Username)),
	}
	for _, key := range keys {
		for _, candidate := range candidates {
			if key == candidate {
				return true
			}
		}
	}
	return false
}

// validateImportDevice enforces the same rules as generation and recomputes
// the fingerprint, so a tampered payload is rejected before any mutation.
func validateImportDevice(device DeviceExportDevice) (DeviceProfile, DeviceMaterial, error) {
	if !deviceIDPattern.MatchString(device.DeviceID) {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("device id is malformed")
	}
	profile, ok := DeviceProfileByName(device.Profile)
	if !ok {
		return DeviceProfile{}, DeviceMaterial{}, fmt.Errorf("profile %q is unknown", device.Profile)
	}
	if device.Platform != profile.Family {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("platform does not match the profile family")
	}
	if !validDeviceAlgorithm(device.Algorithm) {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("algorithm is unknown")
	}
	if !isLowerHex(device.MachineCode, 64) {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("machine code is malformed")
	}
	fingerprint := device.Fingerprint
	if !strings.HasPrefix(fingerprint, "sha256:") {
		fingerprint = "sha256:" + fingerprint
	}
	if !isSHA256Hex(fingerprint) {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("fingerprint is malformed")
	}
	accountKey := device.AccountKey
	if accountKey != "" {
		if !strings.HasPrefix(accountKey, "sha256:") {
			accountKey = "sha256:" + accountKey
		}
		if !isSHA256Hex(accountKey) {
			return DeviceProfile{}, DeviceMaterial{}, errors.New("account key is malformed")
		}
	}
	aliases := make([]string, 0, len(device.AccountKeyAliases))
	for _, alias := range device.AccountKeyAliases {
		if !strings.HasPrefix(alias, "sha256:") {
			alias = "sha256:" + alias
		}
		if !isSHA256Hex(alias) {
			return DeviceProfile{}, DeviceMaterial{}, errors.New("account key alias is malformed")
		}
		aliases = appendDeviceAlias(aliases, alias)
	}
	for _, stamp := range []*string{device.PresentedAt, device.FirstSeenAt, device.LastSeenAt} {
		if stamp != nil && !validRFC3339(*stamp) {
			return DeviceProfile{}, DeviceMaterial{}, errors.New("timestamp is not RFC 3339")
		}
	}
	if device.CreatedAt != "" && !validRFC3339(device.CreatedAt) {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("createdAt is not RFC 3339")
	}
	if device.LoginCount < 0 {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("login count is negative")
	}
	if len(device.Label) > 80 {
		return DeviceProfile{}, DeviceMaterial{}, errors.New("label is too long")
	}
	material := DeviceMaterial{
		Format: DeviceMaterialFormat, Version: DeviceMaterialVersion,
		DeviceID: device.DeviceID, MachineCode: device.MachineCode, Identity: device.Identity,
		Platform: device.Platform, Profile: device.Profile, Algorithm: device.Algorithm,
		Fingerprint: fingerprint, CreatedAt: device.CreatedAt,
		PresentedAt: cloneStringPtr(device.PresentedAt),
		AccountKey:  accountKey, AccountKeyAliases: aliases,
	}
	if err := validateDeviceMaterial(profile, material); err != nil {
		return DeviceProfile{}, DeviceMaterial{}, err
	}
	return profile, material, nil
}

// DeviceGenerateInput is one batch generation request.
type DeviceGenerateInput struct {
	Count       int
	Platform    model.Platform
	Profile     string
	Algorithm   string
	LabelPrefix string
	Seed        []byte
	DimMode     string
	Actor       string
}

// GenerateDevices creates count sealed, unbound records. Validation, sealing
// and insertion are all-or-nothing: a failure leaves the pool untouched.
func (s *Store) GenerateDevices(in DeviceGenerateInput) ([]DeviceRecord, error) {
	if s.deviceSealer == nil {
		return nil, devicePoolDisabled()
	}
	profileName := strings.TrimSpace(in.Profile)
	if profileName == "" {
		profileName = DevicePoolDefaultProfile
	}
	profile, ok := DeviceProfileByName(profileName)
	if !ok {
		return nil, deviceInvalidf(DeviceReasonProfileMismatch, "unknown device profile %q", profileName)
	}
	if in.Platform != "" && in.Platform != profile.Family {
		return nil, deviceInvalidf(DeviceReasonProfileMismatch,
			"profile %q is a %s profile, not %s", profileName, profile.Family, in.Platform)
	}
	s.mu.RLock()
	cfg := s.deviceCfg
	s.mu.RUnlock()
	algorithm := in.Algorithm
	if algorithm == "" {
		algorithm = cfg.Algorithm
	}
	generator, ok := DeviceGeneratorByName(algorithm)
	if !ok {
		return nil, deviceInvalidf(DeviceReasonAlgorithmUnknown, "unknown device algorithm %q", algorithm)
	}
	dimMode := in.DimMode
	if dimMode == "" {
		dimMode = cfg.DimMode
	}
	seed := in.Seed
	if len(seed) == 0 {
		seed = cfg.Seed
	}
	if algorithm == DeviceAlgorithmHMAC && len(seed) > 0 && len(seed) < 16 {
		return nil, deviceInvalidf(DeviceReasonSeedInvalid, "device seed must be at least 16 bytes")
	}
	count := in.Count
	if count <= 0 {
		count = 1
	}
	if count > 100 {
		return nil, invalidf("device generation count must be between 1 and 100")
	}
	actor := strings.TrimSpace(in.Actor)
	if actor == "" {
		actor = "operator"
	}

	materials := make([]DeviceMaterial, 0, count)
	for i := range count {
		material, err := generator.Generate(DeviceGenerateSpec{
			Profile: profile, Index: uint32(i), Seed: seed, DimMode: dimMode,
		})
		if err != nil {
			return nil, err
		}
		materials = append(materials, material)
	}

	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.RLock()
	total := len(s.devicePool)
	s.mu.RUnlock()
	if total+count > cfg.Max {
		return nil, deviceConflictf(DeviceReasonPoolFull,
			"device pool would exceed its limit of %d records", cfg.Max)
	}

	now := iso(s.now())
	records := make([]DeviceRecord, 0, count)
	sealedIDs := make([]string, 0, count)
	for i := range materials {
		material := &materials[i]
		s.mu.RLock()
		material.DeviceID = s.newDeviceIDLocked()
		s.mu.RUnlock()
		if material.DeviceID == "" {
			s.rollbackDeviceSeals(sealedIDs)
			return nil, fmt.Errorf("store: device id generation failed")
		}
		material.CreatedAt = now
		label := strings.TrimSpace(in.LabelPrefix)
		if label != "" && count > 1 {
			label = fmt.Sprintf("%s-%d", label, i+1)
		}
		if err := s.sealDeviceMaterial(*material); err != nil {
			s.rollbackDeviceSeals(sealedIDs)
			return nil, err
		}
		sealedIDs = append(sealedIDs, material.DeviceID)
		records = append(records, DeviceRecord{
			ID:          material.DeviceID,
			Label:       label,
			State:       DeviceAvailable,
			Platform:    profile.Family,
			Profile:     profile.Name,
			Algorithm:   algorithm,
			Fingerprint: material.Fingerprint,
			Hashes:      deviceHashes(material.Identity, material.MachineCode),
			Claims:      deviceClaims(material.Identity),
			CreatedAt:   material.CreatedAt,
			CreatedBy:   actor,
			History: []DeviceEvent{{
				At: now, Action: "created", Actor: actor,
				Detail: "algorithm=" + algorithm + " profile=" + profile.Name,
			}},
		})
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	if len(s.devicePool)+len(records) > cfg.Max {
		s.rollbackDeviceSeals(sealedIDs)
		return nil, deviceConflictf(DeviceReasonPoolFull,
			"device pool would exceed its limit of %d records", cfg.Max)
	}
	for i := range records {
		if err := s.deviceRecordUniqueLocked(&records[i], records[:i]); err != nil {
			s.rollbackDeviceSeals(sealedIDs)
			return nil, err
		}
	}
	for i := range records {
		rec := records[i]
		s.devicePool[rec.ID] = &rec
		s.deviceMaterial[rec.ID] = cloneDeviceMaterial(materials[i])
	}
	target := "pool"
	if len(records) > 0 {
		target = records[0].ID
	}
	s.addAuditLocked(model.SeverityInfo, actor, "device.create", target,
		fmt.Sprintf("profile=%s algorithm=%s count=%d", profile.Name, algorithm, len(records)))
	out := make([]DeviceRecord, len(records))
	for i, rec := range records {
		out[i] = cloneDeviceRecord(rec)
	}
	return out, nil
}

func (s *Store) rollbackDeviceSeals(ids []string) {
	for _, id := range ids {
		_ = s.deleteDeviceMaterial(id)
	}
}

// deviceRecordUniqueLocked rejects a duplicate fingerprint, machine hash or
// vendor id tuple against the pool and the earlier records of the same batch.
// Callers hold the write lock.
func (s *Store) deviceRecordUniqueLocked(candidate *DeviceRecord, batch []DeviceRecord) error {
	existing := make([]DeviceRecord, 0, len(s.devicePool)+len(batch))
	for _, rec := range s.devicePool {
		existing = append(existing, *rec)
	}
	existing = append(existing, batch...)
	for _, rec := range existing {
		if rec.Fingerprint == candidate.Fingerprint {
			return deviceConflictf(DeviceReasonDuplicate, "device fingerprint already exists in the pool")
		}
		if machine := candidate.Hashes["machine"]; machine != "" && rec.Hashes["machine"] == machine {
			return deviceConflictf(DeviceReasonDuplicate, "device machine code already exists in the pool")
		}
		if deviceTupleEqual(rec.Hashes, candidate.Hashes) {
			return deviceConflictf(DeviceReasonDuplicate, "device identity already exists in the pool")
		}
	}
	return nil
}

func deviceTupleEqual(a, b map[string]string) bool {
	for _, key := range []string{"uid", "osdid", "cuid", "cseid"} {
		if a[key] == "" || a[key] != b[key] {
			return false
		}
	}
	return true
}

// --- lifecycle ---

// AssignDevice binds an available record, or a retired record that belongs to
// the same account key (a manual restore). It never marks the identity as
// presented: only a login does that.
func (s *Store) AssignDevice(deviceID, accountID string) (DeviceRecord, error) {
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.Lock()
	defer s.mu.Unlock()

	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", deviceID)
	}
	if s.accountIndexLocked(accountID) < 0 {
		return DeviceRecord{}, notFoundf("account %q not found", accountID)
	}
	idx := s.accountIndexLocked(accountID)
	if boundID, ok := s.deviceBindings[accountID]; ok {
		return DeviceRecord{}, deviceConflictf(DeviceReasonAlreadyBound,
			"account %q is already bound to device %q", accountID, boundID)
	}
	switch rec.State {
	case DeviceAvailable:
		if rec.PresentedAt != nil {
			return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
				"device %q has been presented to the vendor and cannot be reassigned", deviceID)
		}
	case DeviceRetired:
		if !s.deviceAccountMatchesLocked(rec, accountID) {
			return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
				"device %q was retired for a different account key", deviceID)
		}
		if deviceExpired(*rec, s.now(), s.deviceCfg.RetentionDays) {
			return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
				"device %q is past its retention window", deviceID)
		}
	default:
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is %s and cannot be assigned", deviceID, rec.State)
	}
	material, err := s.deviceMaterialLocked(rec)
	if err != nil {
		return DeviceRecord{}, err
	}
	now := iso(s.now())
	accountKey := deviceAccountKey(rec.Platform, s.accounts[idx].Username)
	alias := deviceAccountKey(rec.Platform, strings.ToLower(s.accounts[idx].Username))
	if material.AccountKey != accountKey || len(material.AccountKeyAliases) == 0 {
		material.AccountKey = accountKey
		material.AccountKeyAliases = appendDeviceAlias(material.AccountKeyAliases, alias)
		if err := s.sealDeviceMaterial(material); err != nil {
			return DeviceRecord{}, err
		}
	}
	rec.AccountKey = accountKey
	rec.AccountKeyAliases = appendDeviceAlias(rec.AccountKeyAliases, alias)
	s.deviceMaterial[rec.ID] = cloneDeviceMaterial(material)
	rec.State = DeviceAssigned
	rec.AssignedAccountID = accountID
	rec.AssignedAt = &now
	rec.RetiredAt = nil
	rec.RetiredReason = ""
	s.deviceBindings[accountID] = rec.ID
	s.devices[accountID] = material.Identity
	s.deviceAppendEventLocked(rec, "assigned", "operator", "source=manual")
	s.addAuditLocked(model.SeverityInfo, "operator", "device.assign", rec.ID,
		"account="+s.deviceAccountLabelLocked(accountID)+" source=manual")
	return cloneDeviceRecord(*rec), nil
}

// ReleaseDevice unbinds an assigned record. A record that has ever been
// presented to the vendor is retired, never returned to available.
func (s *Store) ReleaseDevice(deviceID string) (DeviceRecord, error) {
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.Lock()
	defer s.mu.Unlock()

	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", deviceID)
	}
	if rec.State != DeviceAssigned {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is %s and cannot be released", deviceID, rec.State)
	}
	accountID := rec.AssignedAccountID
	if s.deviceLiveNodeLocked(accountID) {
		return DeviceRecord{}, deviceConflictf(DeviceReasonActiveSession,
			"account %q has a live node; log out before releasing its device", accountID)
	}
	label := s.deviceAccountLabelLocked(accountID)
	now := iso(s.now())
	delete(s.deviceBindings, accountID)
	delete(s.devices, accountID)
	rec.AssignedAccountID = ""
	rec.AssignedAt = nil
	reused := rec.PresentedAt == nil
	if reused {
		rec.State = DeviceAvailable
		rec.RetiredAt = nil
		rec.RetiredReason = ""
	} else {
		rec.State = DeviceRetired
		rec.RetiredAt = &now
		rec.RetiredReason = "released_after_presentation"
	}
	s.deviceAppendEventLocked(rec, "released", "operator", "account="+label)
	s.addAuditLocked(model.SeverityInfo, "operator", "device.release", rec.ID,
		fmt.Sprintf("account=%s reused=%t", label, reused))
	return cloneDeviceRecord(*rec), nil
}

// RetireDevice moves an unassigned or logged-out record to retired. It never
// deletes material: restore inside the retention window still works.
func (s *Store) RetireDevice(deviceID, reason string) (DeviceRecord, error) {
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.Lock()
	defer s.mu.Unlock()

	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", deviceID)
	}
	if rec.State == DeviceQuarantined {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is quarantined; purge it instead", deviceID)
	}
	if rec.State == DeviceAssigned {
		if s.deviceLiveNodeLocked(rec.AssignedAccountID) {
			return DeviceRecord{}, deviceConflictf(DeviceReasonActiveSession,
				"account %q has a live node; log out before retiring its device", rec.AssignedAccountID)
		}
		delete(s.deviceBindings, rec.AssignedAccountID)
		delete(s.devices, rec.AssignedAccountID)
		rec.AssignedAccountID = ""
		rec.AssignedAt = nil
	}
	reason = strings.TrimSpace(reason)
	if reason == "" {
		reason = "operator"
	}
	now := iso(s.now())
	rec.State = DeviceRetired
	rec.RetiredAt = &now
	rec.RetiredReason = reason
	s.deviceAppendEventLocked(rec, "retired", "operator", "reason="+reason)
	s.addAuditLocked(model.SeverityInfo, "operator", "device.retire", rec.ID, "reason="+reason)
	return cloneDeviceRecord(*rec), nil
}

// QuarantineDevice freezes an unassigned record. It has no restore edge.
func (s *Store) QuarantineDevice(deviceID, reason string) (DeviceRecord, error) {
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.Lock()
	defer s.mu.Unlock()

	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", deviceID)
	}
	if rec.State == DeviceAssigned {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is assigned; release it before quarantining", deviceID)
	}
	if rec.State == DeviceQuarantined {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is already quarantined", deviceID)
	}
	reason = strings.TrimSpace(reason)
	if reason == "" {
		reason = "operator"
	}
	rec.State = DeviceQuarantined
	rec.RetiredAt = nil
	rec.RetiredReason = ""
	s.deviceAppendEventLocked(rec, "quarantined", "operator", "reason="+reason)
	s.addAuditLocked(model.SeverityWarn, "operator", "device.quarantine", rec.ID, "reason="+reason)
	return cloneDeviceRecord(*rec), nil
}

// PurgeDevice deletes the sealed material and then the record. It is the
// irreversible right-to-erasure path.
func (s *Store) PurgeDevice(deviceID string) error {
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()

	s.mu.RLock()
	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		s.mu.RUnlock()
		return deviceNotFoundf("device %q not found", deviceID)
	}
	if rec.State == DeviceAssigned {
		s.mu.RUnlock()
		return deviceConflictf(DeviceReasonStateInvalid,
			"device %q is assigned; rotate or release it before purging", deviceID)
	}
	s.mu.RUnlock()

	// Sealed entry first: if it fails the record stays and the operator can
	// retry, so the index never points at material that was already removed.
	if err := s.deleteDeviceMaterial(deviceID); err != nil {
		return err
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	rec = s.deviceRecordLocked(deviceID)
	if rec == nil {
		return deviceNotFoundf("device %q not found", deviceID)
	}
	if rec.State == DeviceAssigned {
		return deviceConflictf(DeviceReasonStateInvalid,
			"device %q is assigned; rotate or release it before purging", deviceID)
	}
	delete(s.devicePool, deviceID)
	delete(s.deviceMaterial, deviceID)
	delete(s.devices, rec.AssignedAccountID)
	s.addAuditLocked(model.SeverityWarn, "operator", "device.purge", deviceID, "reason=purge")
	return nil
}

// RestoreCandidate is one retired record that matches an account key.
type RestoreCandidate struct {
	DeviceID      string `json:"deviceId"`
	Fingerprint   string `json:"fingerprint"`
	RetiredAt     string `json:"retiredAt,omitempty"`
	RetiredReason string `json:"retiredReason,omitempty"`
	Profile       string `json:"profile"`
}

// RestoreCandidates lists retired, unexpired records matching the account's
// key in the requested profile family. It performs no mutation.
func (s *Store) RestoreCandidates(accountID, profileName string) ([]RestoreCandidate, error) {
	profileName = strings.TrimSpace(profileName)
	if profileName == "" {
		profileName = DevicePoolDefaultProfile
	}
	profile, ok := DeviceProfileByName(profileName)
	if !ok {
		return nil, deviceInvalidf(DeviceReasonProfileMismatch, "unknown device profile %q", profileName)
	}
	s.mu.RLock()
	defer s.mu.RUnlock()
	idx := s.accountIndexLocked(accountID)
	if idx < 0 {
		return nil, notFoundf("account %q not found", accountID)
	}
	if _, bound := s.deviceBindings[accountID]; bound {
		return nil, nil
	}
	keys := []string{
		deviceAccountKey(profile.Family, s.accounts[idx].Username),
		deviceAccountKey(profile.Family, strings.ToLower(s.accounts[idx].Username)),
	}
	records := s.restoreCandidatesLocked(keys, profile.Family)
	out := make([]RestoreCandidate, 0, len(records))
	for _, rec := range records {
		candidate := RestoreCandidate{
			DeviceID: rec.ID, Fingerprint: rec.Fingerprint, Profile: rec.Profile,
			RetiredReason: rec.RetiredReason,
		}
		if rec.RetiredAt != nil {
			candidate.RetiredAt = *rec.RetiredAt
		}
		out = append(out, candidate)
	}
	return out, nil
}

// restoreCandidatesLocked returns matching tombstones, newest retirement
// first. Callers hold at least the read lock.
func (s *Store) restoreCandidatesLocked(keys []string, family model.Platform) []DeviceRecord {
	out := []DeviceRecord{}
	now := s.now()
	for _, rec := range s.devicePool {
		if rec.State != DeviceRetired || rec.AssignedAccountID != "" {
			continue
		}
		if rec.Platform != family || !deviceRecordHasKey(rec, keys) {
			continue
		}
		if deviceExpired(*rec, now, s.deviceCfg.RetentionDays) {
			continue
		}
		out = append(out, cloneDeviceRecord(*rec))
	}
	sort.Slice(out, func(i, j int) bool {
		left, right := "", ""
		if out[i].RetiredAt != nil {
			left = *out[i].RetiredAt
		}
		if out[j].RetiredAt != nil {
			right = *out[j].RetiredAt
		}
		if left != right {
			return left > right
		}
		return out[i].ID < out[j].ID
	})
	return out
}

// RestoreDevice binds a specific retired record to an account. It is the
// operator's resolution for an ambiguous automatic match.
func (s *Store) RestoreDevice(deviceID, accountID string) (DeviceRecord, error) {
	s.deviceMu.Lock()
	defer s.deviceMu.Unlock()
	s.mu.Lock()
	defer s.mu.Unlock()

	rec := s.deviceRecordLocked(deviceID)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", deviceID)
	}
	if s.accountIndexLocked(accountID) < 0 {
		return DeviceRecord{}, notFoundf("account %q not found", accountID)
	}
	if boundID, ok := s.deviceBindings[accountID]; ok {
		return DeviceRecord{}, deviceConflictf(DeviceReasonAlreadyBound,
			"account %q is already bound to device %q", accountID, boundID)
	}
	if rec.State != DeviceRetired {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is %s and cannot be restored", deviceID, rec.State)
	}
	if !s.deviceAccountMatchesLocked(rec, accountID) {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q was retired for a different account key", deviceID)
	}
	if deviceExpired(*rec, s.now(), s.deviceCfg.RetentionDays) {
		return DeviceRecord{}, deviceConflictf(DeviceReasonStateInvalid,
			"device %q is past its retention window", deviceID)
	}
	material, err := s.deviceMaterialLocked(rec)
	if err != nil {
		return DeviceRecord{}, err
	}
	now := iso(s.now())
	rec.State = DeviceAssigned
	rec.AssignedAccountID = accountID
	rec.AssignedAt = &now
	rec.RetiredAt = nil
	rec.RetiredReason = ""
	s.deviceBindings[accountID] = rec.ID
	s.devices[accountID] = material.Identity
	s.deviceAppendEventLocked(rec, "restored", "operator", "source=manual")
	s.addAuditLocked(model.SeverityInfo, "operator", "device.restore", rec.ID,
		"account="+s.deviceAccountLabelLocked(accountID)+" candidate=manual")
	return cloneDeviceRecord(*rec), nil
}
