// ErrDeviceMaterialMissing is returned when an account is bound to a record
// whose sealed material cannot be opened. Login fails closed: a missing
// identity is never silently regenerated.
var ErrDeviceMaterialMissing = errors.New("store: device material missing")

// DeviceError carries a stable reason alongside the store error kind.
type DeviceError struct {
	Kind    error
	Reason  string
	Message string
}

func (e *DeviceError) Error() string { return e.Message }

// Unwrap keeps errors.Is(err, store.ErrConflict) working for the API layer.
func (e *DeviceError) Unwrap() error { return e.Kind }

// DeviceReason returns the stable machine code of a DeviceError, or "".
func (e *DeviceError) DeviceReason() string { return e.Reason }

func deviceErrorf(kind error, reason, format string, args ...any) error {
	return &DeviceError{Kind: kind, Reason: reason, Message: fmt.Sprintf(format, args...)}
}

// DeviceErrorReason extracts the stable reason from any error in the chain.
func DeviceErrorReason(err error) string {
	var typed *DeviceError
	if errors.As(err, &typed) {
		return typed.Reason
	}
	var conflict *DeviceImportConflictError
	if errors.As(err, &conflict) {
		return DeviceReasonImportConflict
	}
	return ""
}

func deviceNotFoundf(format string, args ...any) error {
	return deviceErrorf(ErrNotFound, DeviceReasonNotFound, format, args...)
}

func deviceInvalidf(reason, format string, args ...any) error {
	return deviceErrorf(ErrInvalid, reason, format, args...)
}

func deviceConflictf(reason, format string, args ...any) error {
	return deviceErrorf(ErrConflict, reason, format, args...)
}

func deviceMaterialMissingf(format string, args ...any) error {
	return deviceErrorf(ErrDeviceMaterialMissing, DeviceReasonMaterialMissing, format, args...)
}

func devicePoolDisabled() error {
	return deviceErrorf(ErrConflict, DeviceReasonPoolDisabled, "device pool is disabled: no device sealer configured")
}

// DeviceState is the pool state machine.
type DeviceState string

const (
	DeviceAvailable   DeviceState = "available"   // generated, never presented to the vendor
	DeviceAssigned    DeviceState = "assigned"    // bound to exactly one account
	DeviceRetired     DeviceState = "retired"     // unbound, retained for restore
	DeviceQuarantined DeviceState = "quarantined" // never reused
)

func validDeviceState(state DeviceState) bool {
	switch state {
	case DeviceAvailable, DeviceAssigned, DeviceRetired, DeviceQuarantined:
		return true
	default:
		return false
	}
}

