// DevicePoolQuery filters ListDevicePool.
type DevicePoolQuery struct {
	State     DeviceState
	Platform  model.Platform
	Profile   string
	AccountID string
	Query     string
	Limit     int
	Offset    int
}

// DevicePoolView is the pool list response shape (DESIGN-DEVICE-POOL §8.2).
type DevicePoolView struct {
	Enabled  bool           `json:"enabled"`
	Total    int            `json:"total"`
	Counts   map[string]int `json:"counts"`
	Devices  []DeviceRecord `json:"devices"`
	Warnings []string       `json:"warnings,omitempty"`
}

// ListDevicePool returns the filtered page. Total and Counts describe the
// whole pool, not the page.
func (s *Store) ListDevicePool(q DevicePoolQuery) DevicePoolView {
	s.mu.RLock()
	defer s.mu.RUnlock()
	view := DevicePoolView{
		Enabled: s.deviceSealer != nil,
		Total:   len(s.devicePool),
		Counts: map[string]int{
			string(DeviceAvailable): 0, string(DeviceAssigned): 0,
			string(DeviceRetired): 0, string(DeviceQuarantined): 0,
		},
		Devices:  []DeviceRecord{},
		Warnings: append([]string(nil), s.deviceWarnings...),
	}
	needle := strings.ToLower(strings.TrimSpace(q.Query))
	for _, rec := range s.devicePool {
		view.Counts[string(rec.State)]++
		if q.State != "" && rec.State != q.State {
			continue
		}
		if q.Platform != "" && rec.Platform != q.Platform {
			continue
		}
		if q.Profile != "" && rec.Profile != q.Profile {
			continue
		}
		if q.AccountID != "" && rec.AssignedAccountID != q.AccountID {
			continue
		}
		if needle != "" {
			haystack := strings.ToLower(rec.ID + " " + rec.Label + " " + rec.Notes + " " + rec.AssignedAccountID)
			if !strings.Contains(haystack, needle) {
				continue
			}
		}
		view.Devices = append(view.Devices, cloneDeviceRecord(*rec))
	}
	sort.Slice(view.Devices, func(i, j int) bool {
		if view.Devices[i].CreatedAt != view.Devices[j].CreatedAt {
			return view.Devices[i].CreatedAt < view.Devices[j].CreatedAt
		}
		return view.Devices[i].ID < view.Devices[j].ID
	})
	offset := q.Offset
	if offset < 0 {
		offset = 0
	}
	if offset > len(view.Devices) {
		offset = len(view.Devices)
	}
	limit := q.Limit
	if limit <= 0 {
		limit = 50
	}
	if limit > 200 {
		limit = 200
	}
	end := offset + limit
	if end > len(view.Devices) {
		end = len(view.Devices)
	}
	view.Devices = view.Devices[offset:end]
	return view
}

// UpdateDevice changes the operator label and notes. Neither may carry a raw
// identity; they are free text and are persisted.
func (s *Store) UpdateDevice(id string, label, notes *string) (DeviceRecord, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	rec := s.deviceRecordLocked(id)
	if rec == nil {
		return DeviceRecord{}, deviceNotFoundf("device %q not found", id)
	}
	if label != nil {
		value := strings.TrimSpace(*label)
		if len(value) > 80 {
			return DeviceRecord{}, invalidf("device label must be at most 80 characters")
		}
		rec.Label = value
	}
	if notes != nil {
		if len(*notes) > 500 {
			return DeviceRecord{}, invalidf("device notes must be at most 500 characters")
		}
		rec.Notes = *notes
	}
	return cloneDeviceRecord(*rec), nil
}

